import re, sys, json
css_path, pack_path, xterm_path, out = sys.argv[1:5]
css = open(css_path, encoding='utf8').read()
VARS = ['bg','bg-elevated','bg-sunken','panel','panel-hover','border','border-strong','fg','fg-muted','fg-faint','text-quaternary','accent','accent-strong','accent-on','accent-soft','accent-border','status-working','status-waiting','status-stopped','status-offline','agent-shell','agent-claude','agent-codex','agent-opencode']
themes = {}
order = []
for m in re.finditer(r"((?:\[data-theme='[^']+'\]\s*,?\s*|:root\s*,\s*)+)\{([^}]*)\}", css):
    names = re.findall(r"data-theme='([^']+)'", m.group(1))
    body = m.group(2)
    vals = dict(re.findall(r"--([a-z0-9-]+)\s*:\s*([^;]+);", body))
    for n in names:
        if n not in themes:
            themes[n] = {}; order.append(n)
        themes[n].update(vals)
# theme-pack dark-lemon
pack = open(pack_path, encoding='utf8').read()
i = pack.index("id: 'dark-lemon'")
seg = pack[i: pack.index("terminal:", i)]
themes['dark-lemon'] = dict(re.findall(r"'--([a-z0-9-]+)':\s*'([^']+)'", seg)); order.append('dark-lemon')
term_seg = pack[pack.index("terminal:", i): pack.index("}", pack.index("terminal:", i))]
pack_term = dict(re.findall(r"(\w+):\s*'([^']+)'", term_seg))
base = themes['dark']
def color(v):
    v = v.strip()
    m = re.match(r"#([0-9a-fA-F]{6})([0-9a-fA-F]{2})?$", v)
    if m:
        h = m.group(1); a = int(m.group(2),16) if m.group(2) else 255
        return f"rgba({int(h[0:2],16)}, {int(h[2:4],16)}, {int(h[4:6],16)}, {a})"
    m = re.match(r"#([0-9a-fA-F]{3})$", v)
    if m:
        h=m.group(1); return f"rgba({int(h[0]*2,16)}, {int(h[1]*2,16)}, {int(h[2]*2,16)}, 255)"
    m = re.match(r"rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+))?\s*\)", v)
    if m:
        a = round(float(m.group(4))*255) if m.group(4) else 255
        return f"rgba({m.group(1)}, {m.group(2)}, {m.group(3)}, {a})"
    return None
lines = ["// @generated by tools/gen_themes.py from alethe-agents src/styles/theme.css,", "// src/plugins/theme-pack/themes.ts and src/components/XTermView/xtermThemes.ts.", "use super::{rgba, TermPalette, UiTokens};", "", "pub const UI_THEMES: &[(&str, UiTokens)] = &["]
for n in order:
    t = dict(base); t.update(themes[n])
    lines.append(f"    (\"{n}\", UiTokens {{")
    for v in VARS:
        val = t.get(v) or base.get(v)
        c = color(val) if val else None
        if c is None:
            c = color(base[v])
        lines.append(f"        {v.replace('-','_')}: {c},")
    lines.append("    }),")
lines.append("];")
# xterm themes
x = open(xterm_path, encoding='utf8').read()
consts = {}
for m in re.finditer(r"const (\w+) = \{(.*?)\} as const", x, re.S):
    consts[m.group(1)] = m.group(2)
def parse_obj(name):
    body = consts[name]; d = {}
    for line in body.splitlines():
        line=line.strip()
        sm = re.match(r"\.\.\.(\w+)", line)
        if sm: d.update(parse_obj(sm.group(1))); continue
        km = re.match(r"(\w+):\s*'([^']+)'", line)
        if km: d[km.group(1)] = km.group(2)
    return d
mapping = dict(re.findall(r"'?([\w-]+)'?:\s*(\w+_THEME),", x[x.index("const XTERM_THEMES"):]))
mapping['dark-lemon'] = None
KEYS = ['black','red','green','yellow','blue','magenta','cyan','white','brightBlack','brightRed','brightGreen','brightYellow','brightBlue','brightMagenta','brightCyan','brightWhite']
# xterm.js default ANSI
DEFAULT = dict(zip(KEYS, ['#2e3436','#cc0000','#4e9a06','#c4a000','#3465a4','#75507b','#06989a','#d3d7cf','#555753','#ef2929','#8ae234','#fce94f','#729fcf','#ad7fa8','#34e2e2','#eeeeec']))
lines += ["", "pub const TERM_PALETTES: &[(&str, TermPalette)] = &["]
for n, c in mapping.items():
    d = dict(DEFAULT); d.update(parse_obj(c) if c else pack_term)
    lines.append(f"    (\"{n}\", TermPalette {{")
    for k in ['background','foreground','cursor','selectionBackground']:
        lines.append(f"        {re.sub(r'([A-Z])', lambda m: '_'+m.group(1).lower(), k)}: {color(d[k])},")
    lines.append("        ansi: [" + ", ".join(color(d[k]) for k in KEYS) + "],")
    lines.append("    }),")
lines.append("];")
open(out,'w',encoding='utf8').write("\n".join(lines)+"\n")
print(order, list(mapping))
